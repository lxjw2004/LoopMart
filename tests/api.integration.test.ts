import { processNotificationJobs } from '../apps/api/src/notifications.js';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { getMigrations } from 'better-auth/db/migration';
import { Pool } from 'pg';
import { migrate } from '../packages/database/src/migrate.js';
import { createAuth } from '../apps/auth/src/auth.js';
import { createApp } from '../apps/api/src/app.js';
const databaseURL = process.env.TEST_DATABASE_URL;
test('real PostgreSQL and Better Auth business authorization, chat and admin transactions', { skip: !databaseURL }, async () => {
    const pool = new Pool({ connectionString: databaseURL });
    const mail: any[] = [];
    const auth = createAuth({ databaseURL: databaseURL!, secret: 'integration-secret-at-least-thirty-two-characters', baseURL: 'http://localhost:3001', trustedOrigins: ['http://localhost:3001'], domains: ['purdue.edu'], mail: { url: undefined, from: undefined } }, pool, async (message) => { mail.push(message); });
    const migrations = await getMigrations(auth.options);
    await migrations.runMigrations();
    await migrate(pool);
    await migrate(pool);
    const server = createServer(createApp({ pool, auth, origin: 'http://localhost:3001' }));
    await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
    const address = server.address() as any;
    const base = `http://127.0.0.1:${address.port}/api/v1`;
    const request = async (path: string, method = 'GET', body?: any, cookie = '') => { const r = await fetch(base + path, { method, headers: { 'content-type': 'application/json', cookie }, body: body === undefined ? undefined : JSON.stringify(body) }); return { status: r.status, ...await r.json() as any }; };
    async function account() { const email = `api-${crypto.randomUUID()}@purdue.edu`; await auth.api.signUpEmail({ body: { email, password: 'Strong-password-12345', name: 'Member' } }); const text = mail.at(-1).text; const token = new URL(text).searchParams.get('token')!; await auth.api.verifyEmail({ query: { token } }); const response = await auth.api.signInEmail({ body: { email, password: 'Strong-password-12345' }, asResponse: true }); const cookie = response.headers.getSetCookie().map(v => v.split(';')[0]).join('; '); const user = (await pool.query('SELECT id FROM "user" WHERE email=$1', [email])).rows[0]; return { id: user.id, cookie }; }
    try {
        const a = await account(), b = await account(), c = await account();
        const item = { title: 'Desk', description: 'A desk', category: 'furniture', condition: 'good', deliveryMethod: 'pickup', priceCents: 100 };
        assert.equal((await request('/items', 'POST', item)).status, 401);
        assert.equal((await request('/items', 'POST', { ...item, priceCents: 1.5 }, a.cookie)).status, 400);
        const created = await request('/items', 'POST', item, a.cookie);
        assert.equal(created.status, 200);
        const id = created.data.id;
        assert.equal((await request('/items/' + id, 'PATCH', { title: 'stolen' }, b.cookie)).status, 403);
        assert.equal((await request('/items/' + id)).data.title, 'Desk');
        assert.equal((await request('/settings', 'PATCH', { contactEnabled: false }, a.cookie)).status, 403);
        const first = await request('/conversations', 'POST', { otherUserId: b.id }, a.cookie);
        const second = await request('/conversations', 'POST', { otherUserId: a.id }, b.cookie);
        assert.equal(first.status, 200, JSON.stringify(first));
        assert.equal(second.status, 200, JSON.stringify(second));
        assert.equal(first.data.id, second.data.id);
        const conversation = first.data.id;
        assert.equal((await request(`/conversations/${conversation}/messages`, 'GET', undefined, c.cookie)).status, 403);
        const payload = { clientId: 'same', text: 'Hello', reference: { type: 'item', id } };
        const m1 = await request(`/conversations/${conversation}/messages`, 'POST', payload, a.cookie);
        const m2 = await request(`/conversations/${conversation}/messages`, 'POST', payload, a.cookie);
        assert.equal(m1.data.id, m2.data.id);
        assert.equal((await request(`/conversations/${conversation}/messages`, 'POST', { ...payload, text: 'Changed' }, a.cookie)).status, 409);
        assert.equal((await request('/items/not-a-uuid')).status, 400);
        assert.equal((await request('/items', 'POST', { ...item, communityId: 'other' }, a.cookie)).data.communityId, 'purdue');
        assert.equal((await request('/conversations', 'GET', undefined, b.cookie)).data[0].unreadCount, 1);
        assert.equal((await request(`/conversations/${conversation}/read`, 'PUT', { messageId: m1.data.id }, b.cookie)).status, 200);
        assert.equal((await request('/conversations', 'GET', undefined, b.cookie)).data[0].unreadCount, 0);
        await pool.query("UPDATE memberships SET role='admin' WHERE user_id=$1", [a.id]);
        assert.equal((await request('/admin/items/' + id, 'PATCH', { status: 'deactivated_violation', reason: 'Violation' }, a.cookie)).status, 200);
        assert.equal((await request('/items/' + id, 'PATCH', { status: 'active' }, a.cookie)).status, 403);
        assert.equal((await pool.query('SELECT count(*)::int n FROM audit WHERE actor_id=$1', [a.id])).rows[0].n, 1);
        const audit = (await pool.query('SELECT * FROM audit WHERE actor_id=$1', [a.id])).rows[0];
        assert.equal(audit.before_data.status, 'active');
        assert.equal(audit.after_data.status, 'deactivated_violation');
        assert.equal((await request('/admin/settings', 'PATCH', { reason: 'Invalid', contactEnabled: 'bad' }, a.cookie)).status, 400);
        assert.equal((await pool.query('SELECT count(*)::int n FROM audit WHERE actor_id=$1', [a.id])).rows[0].n, 1);
        const ride = { origin: 'Purdue', destination: 'Chicago', departureTime: '2026-11-15T01:00:00Z', timeZone: 'America/Indiana/Indianapolis', feeCents: 1500, totalSeats: 3, availableSeats: 2 };
        assert.equal((await request('/rides', 'POST', { ...ride, availableSeats: 4 }, b.cookie)).status, 400);
        const rideResult = await request('/rides', 'POST', ride, b.cookie);
        assert.equal(rideResult.status, 200);
        assert.equal((await request('/rides?date=2026-11-14')).data.some((r: any) => r.id === rideResult.data.id), true);
        assert.equal((await request('/rides?date=2026-11-15')).data.some((r: any) => r.id === rideResult.data.id), false);
        assert.equal((await request('/favorites/' + rideResult.data.id, 'PUT', {}, b.cookie)).status, 404);
        const fav = await request('/items', 'POST', item, b.cookie);
        assert.equal((await request('/favorites/' + fav.data.id, 'PUT', {}, b.cookie)).status, 200);
        assert.equal((await request('/favorites', 'GET', undefined, b.cookie)).data.some((r: any) => r.id === fav.data.id), true);
        const report = await request('/reports', 'POST', { targetType: 'item', targetId: fav.data.id, reason: 'Misleading', details: '' }, c.cookie);
        assert.equal(report.status, 201);
        assert.equal((await request('/admin/settings', 'PATCH', { communityAdminUserId: a.id, reason: 'Configure notifications' }, a.cookie)).status, 200);
        assert.equal((await request('/admin/reports/' + report.data.id, 'PATCH', { status: 'violation_confirmed', note: 'Confirmed', reason: 'Review' }, a.cookie)).status, 200);
        await processNotificationJobs(pool);
        const notification = (await pool.query("SELECT * FROM notification_jobs WHERE payload->>'userId'=$1 ORDER BY next_attempt_at DESC LIMIT 1", [b.id])).rows[0];
        assert.ok(notification.completed_at);
        assert.equal((await request('/items/' + fav.data.id, 'PATCH', { status: 'active' }, b.cookie)).status, 403);
        const retryId = crypto.randomUUID();
        await pool.query('INSERT INTO notification_jobs(id,payload) VALUES($1,$2)', [retryId, { userId: 'missing-user', text: 'Retry' }]);
        await processNotificationJobs(pool);
        const retry = (await pool.query('SELECT * FROM notification_jobs WHERE id=$1', [retryId])).rows[0];
        assert.equal(retry.attempts, 1);
        assert.ok(retry.last_error);
        assert.equal(retry.completed_at, null);
        const pagingTitle = 'Paging-' + crypto.randomUUID();
        await pool.query("INSERT INTO entities(id,kind,publisher_id,data) SELECT gen_random_uuid(),'item',$1,$2 FROM generate_series(1,52)", [b.id, { ...item, title: pagingTitle }]);
        const page1 = await request('/items?q=' + pagingTitle);
        assert.equal(page1.data.length, 50);
        assert.ok(page1.nextCursor);
        const page2 = await request('/items?q=' + pagingTitle + '&cursor=' + page1.nextCursor);
        assert.equal(page2.data.length, 2);
        assert.equal(page2.nextCursor, null);
        const controller = new AbortController();
        const stream = await fetch(base + '/events', { headers: { cookie: b.cookie }, signal: controller.signal });
        const reader = stream.body!.getReader();
        await reader.read();
        await request(`/conversations/${conversation}/messages`, 'POST', { clientId: crypto.randomUUID(), text: 'Realtime' }, a.cookie);
        const realtime = await reader.read();
        assert.match(new TextDecoder().decode(realtime.value), /event: message/);
        controller.abort();
        const managedEmail = `managed-${crypto.randomUUID()}@purdue.edu`;
        const managed = await request('/admin/users', 'POST', { email: managedEmail, name: 'Managed', password: 'Managed-password-123', reason: 'Provision' }, a.cookie);
        assert.equal(managed.status, 201, JSON.stringify(managed));
        assert.equal(managed.data.emailVerified, false);
        assert.equal((await request('/admin/users/' + managed.data.id + '/password', 'POST', { password: 'Replacement-password-456', reason: 'Rotate' }, a.cookie)).status, 200);
        await pool.query("ALTER TABLE audit ADD CONSTRAINT api_test_audit_rollback CHECK(reason<>'rollback-test')");
        const failedEmail = `failed-${crypto.randomUUID()}@purdue.edu`;
        try {
            assert.equal((await request('/admin/users', 'POST', { email: failedEmail, name: 'Rollback', password: 'Managed-password-123', reason: 'rollback-test' }, a.cookie)).status, 500);
            assert.equal((await pool.query('SELECT id FROM "user" WHERE email=$1', [failedEmail])).rowCount, 0);
        }
        finally {
            await pool.query('ALTER TABLE audit DROP CONSTRAINT api_test_audit_rollback');
        }
    }
    finally {
        server.closeAllConnections();
        await new Promise<void>(resolve => server.close(() => resolve()));
        await pool.end();
    }
});
